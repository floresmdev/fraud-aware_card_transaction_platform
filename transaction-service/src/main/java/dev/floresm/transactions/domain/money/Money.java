package dev.floresm.transactions.domain.money;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.util.Currency;
import java.util.Objects;

/**
 * An amount of money in a specific currency. This is a <b>value object</b>: it has no identity, two
 * instances with the same amount and currency are equal, and it can never change after creation.
 *
 * <h2>Why integer minor units and not {@code double}?</h2>
 * Binary floating point cannot represent most decimal fractions exactly ({@code 0.1 + 0.2 ==
 * 0.30000000000000004}). Rounding errors on money accumulate into real losses and failed
 * reconciliations. We store the amount as a {@code long} count of the currency's smallest unit
 * ("minor units"): 12.34 USD is {@code 1234} cents, 500 JPY is {@code 500} (yen has no minor unit).
 * Integer arithmetic is exact, fast and maps 1:1 to a PostgreSQL {@code BIGINT}. See docs/adr/0002.
 *
 * <h2>Why a Java {@code record}?</h2>
 * A record is a final class whose fields are private and final, with the constructor, accessors,
 * {@code equals}, {@code hashCode} and {@code toString} generated by the compiler. That is exactly
 * what a value object needs. The "compact constructor" below runs validation on every creation, so
 * an invalid {@code Money} can never exist ("make illegal states unrepresentable").
 *
 * @param minorUnits amount in the currency's smallest unit; may be negative (e.g. a refund delta)
 * @param currency   ISO-4217 currency
 */
public record Money(long minorUnits, Currency currency) implements Comparable<Money> {

    public Money {
        Objects.requireNonNull(currency, "currency must not be null");
        if (currency.getDefaultFractionDigits() < 0) {
            // Pseudo-currencies like XAU (gold) have no defined minor unit, so we cannot store them.
            throw new InvalidAmountException("Unsupported currency: " + currency.getCurrencyCode());
        }
    }

    /** Zero in the given currency. Useful as the starting value for sums. */
    public static Money zero(Currency currency) {
        return new Money(0, currency);
    }

    /**
     * Converts a decimal amount as written by a human ("12.34") into minor units.
     *
     * <p>We <b>reject</b> amounts with more decimals than the currency allows (12.345 USD) instead of
     * silently rounding them: rounding money behind the caller's back is a bug, not a convenience.
     */
    public static Money of(BigDecimal amount, Currency currency) {
        Objects.requireNonNull(amount, "amount must not be null");
        Objects.requireNonNull(currency, "currency must not be null");
        int fractionDigits = currency.getDefaultFractionDigits();
        if (fractionDigits < 0) {
            throw new InvalidAmountException("Unsupported currency: " + currency.getCurrencyCode());
        }
        // stripTrailingZeros makes "12.50" and "12.5" both have scale 1, so we check real precision.
        if (amount.stripTrailingZeros().scale() > fractionDigits) {
            throw new InvalidAmountException("Amount %s has more than %d decimal places for %s"
                    .formatted(amount.toPlainString(), fractionDigits, currency.getCurrencyCode()));
        }
        try {
            // movePointRight(2) turns 12.34 into 1234; longValueExact throws if it would overflow.
            return new Money(amount.movePointRight(fractionDigits).longValueExact(), currency);
        } catch (ArithmeticException e) {
            throw new InvalidAmountException("Amount is out of range: " + amount.toPlainString());
        }
    }

    /** Convenience factory from a currency code such as "USD". */
    public static Money of(BigDecimal amount, String currencyCode) {
        return of(amount, parseCurrency(currencyCode));
    }

    /** Parses an ISO-4217 code, translating the JDK's generic exception into a domain one. */
    public static Currency parseCurrency(String currencyCode) {
        try {
            return Currency.getInstance(Objects.requireNonNull(currencyCode, "currency must not be null"));
        } catch (IllegalArgumentException e) {
            throw new InvalidAmountException("Unknown currency: " + currencyCode);
        }
    }

    /** The amount as a decimal, e.g. 1234 cents -> 12.34. Used only at the API boundary. */
    public BigDecimal toDecimal() {
        return BigDecimal.valueOf(minorUnits, currency.getDefaultFractionDigits())
                .setScale(currency.getDefaultFractionDigits(), RoundingMode.UNNECESSARY);
    }

    /**
     * Returns a <b>new</b> Money; {@code this} is never modified (immutability).
     * {@link Math#addExact} throws on overflow instead of silently wrapping around to a negative
     * number, which with money would be catastrophic.
     */
    public Money plus(Money other) {
        requireSameCurrency(other);
        return new Money(Math.addExact(minorUnits, other.minorUnits), currency);
    }

    public Money minus(Money other) {
        requireSameCurrency(other);
        return new Money(Math.subtractExact(minorUnits, other.minorUnits), currency);
    }

    public boolean isPositive() {
        return minorUnits > 0;
    }

    public boolean isNegative() {
        return minorUnits < 0;
    }

    public boolean isGreaterThan(Money other) {
        return compareTo(other) > 0;
    }

    public boolean hasSameCurrencyAs(Money other) {
        return currency.equals(other.currency);
    }

    /**
     * Comparing 10 USD with 10 EUR is meaningless without an exchange rate, so it is an error.
     * Note the contract of {@link Comparable}: negative / zero / positive like {@code a - b}.
     */
    @Override
    public int compareTo(Money other) {
        requireSameCurrency(other);
        return Long.compare(minorUnits, other.minorUnits);
    }

    private void requireSameCurrency(Money other) {
        Objects.requireNonNull(other, "other must not be null");
        if (!hasSameCurrencyAs(other)) {
            throw new IllegalArgumentException("Currency mismatch: %s vs %s"
                    .formatted(currency.getCurrencyCode(), other.currency.getCurrencyCode()));
        }
    }

    @Override
    public String toString() {
        return toDecimal().toPlainString() + " " + currency.getCurrencyCode();
    }
}
